// @ts-check
import { defineConfig, fontProviders } from 'astro/config';
import sitemap from '@astrojs/sitemap';
import tailwindcss from '@tailwindcss/vite';

const site = process.env.SITE_URL ?? 'https://rustle.fxs.life';

// Display type stacks the CJK-only Noto subset first, so Instrument Serif can end
// in a generic family and get a metric-matched fallback (no layout shift on
// swap). Body/mono fallbacks have no CJK glyphs so Chinese reaches the system
// stack in global.css.
const latinSubsets = /** @type {[string, ...string[]]} */ (['latin', 'latin-ext']);

export default defineConfig({
  site,
  trailingSlash: 'ignore',
  // Inline CSS: one fewer render-blocking request on first visit.
  build: { format: 'directory', inlineStylesheets: 'always' },

  i18n: {
    locales: ['zh', 'en'],
    defaultLocale: 'zh',
    routing: { prefixDefaultLocale: false },
  },

  fonts: [
    {
      provider: fontProviders.google(),
      name: 'Instrument Serif',
      cssVariable: '--font-instrument',
      weights: [400],
      styles: ['normal', 'italic'],
      subsets: latinSubsets,
      fallbacks: ['Times New Roman', 'serif'],
    },
    {
      provider: fontProviders.google(),
      name: 'Geist',
      cssVariable: '--font-geist',
      weights: ['300 700'],
      styles: ['normal'],
      subsets: latinSubsets,
      fallbacks: ['Arial'],
    },
    {
      provider: fontProviders.google(),
      name: 'Geist Mono',
      cssVariable: '--font-geist-mono',
      weights: ['400 600'],
      styles: ['normal'],
      subsets: latinSubsets,
      fallbacks: ['Courier New'],
    },
    {
      // Subset generated by scripts/subset-cjk-font.mjs from the site copy.
      provider: fontProviders.local(),
      name: 'Noto Serif SC',
      cssVariable: '--font-noto-serif-sc',
      options: {
        variants: [{ src: ['./src/assets/fonts/noto-serif-sc-subset.woff2'], weight: 500, style: 'normal' }],
      },
      // CJK only: pages whose headings are all Latin never download it.
      unicodeRange: ['U+3000-303F', 'U+4E00-9FFF', 'U+FF00-FFEF'],
      fallbacks: [],
      optimizedFallbacks: false,
    },
  ],

  integrations: [
    sitemap({
      i18n: { defaultLocale: 'zh', locales: { zh: 'zh-CN', en: 'en' } },
      filter: (page) => !page.endsWith('/404/'),
      lastmod: new Date(),
      changefreq: 'weekly',
      serialize: (item) => ({ ...item, priority: new URL(item.url).pathname === '/' ? 1 : 0.9 }),
    }),
  ],

  vite: {
    plugins: [tailwindcss()],
  },
});
